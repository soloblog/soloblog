"""Everything there is to test, listed from the code itself so nothing is
missed: every route, every setting (and whether any screen sets it), every
editor command, every email Soloblog sends, and how many words visitors
see in each language. Markdown on stdout.

    python tools/inventory.py > inventory.md
"""
from pathlib import Path
import os
import re
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("DATA_DIR", tempfile.mkdtemp(prefix="soloblog-inventory-"))
os.environ.setdefault("SESSION_SECRET", "inventory")
os.chdir(ROOT)


def source(*folders):
    out = {}
    for folder in folders:
        for dirpath, _, files in os.walk(os.path.join(ROOT, folder)):
            for name in files:
                if name.endswith(".py"):
                    path = os.path.join(dirpath, name)
                    out[os.path.relpath(path, ROOT)] = Path(path).read_text(encoding="utf-8")
    return out


def main():
    from soloblog.app import app
    from soloblog import editor_config, settings
    from starlette.routing import Route
    code = source("soloblog")
    print("# Inventory\n")
    print("Generated by tools/inventory.py - every row is something to test.\n")

    routes = sorted({(m, r.path) for r in app.routes if isinstance(r, Route) and r.path != "/{fname:path}.{ext:static}"
                     for m in sorted(set(r.methods or ()) - {"HEAD"})}, key=lambda x: (x[1], x[0]))
    print(f"## Routes ({len(routes)})\n")
    for method, path in routes:
        print(f"- [ ] `{method} {path}`")

    screens = "\n".join(text for path, text in code.items() if path.startswith("soloblog/routes/"))
    keys = sorted(settings.DEFAULTS)
    unseen = [k for k in keys if not re.search(rf'["\']{re.escape(k)}["\']', screens)]
    print(f"\n## Settings ({len(keys)}; {len(unseen)} set by no screen)\n")
    print("A setting no screen names is either kept by the app itself (a last-run time, an id at Stripe) "
          "or left over - each of those is a question for phase 5.\n")
    for k in keys:
        print(f"- [ ] `{k}`" + (" - *no screen sets it*" if k in unseen else ""))

    print(f"\n## Editor commands ({len(editor_config.COMMANDS)})\n")
    for c in editor_config.COMMANDS:
        print(f"- [ ] `{c['id']}` - {c['label']} ({c['group']}{', ' + c['keys'] if c['keys'] else ''})")

    print("\n## Emails sent\n")
    for path, text in sorted(code.items()):
        for n, line in enumerate(text.splitlines(), 1):
            if "send_email(" in line and "def send_email" not in line:
                print(f"- [ ] {path}:{n} - `{line.strip()[:110]}`")

    import json
    locales = sorted(os.listdir(os.path.join(ROOT, "soloblog", "locales")))
    words = len(json.loads(Path(os.path.join(ROOT, "soloblog", "locales", locales[0])).read_text(encoding="utf-8")))
    print(f"\n## Words visitors see\n\n{words} phrases, in {len(locales)} translations plus English.\n")


if __name__ == "__main__":
    main()
