"""Makes every daisyUI theme Soloblog offers readable, and writes the
result to static/css/contrast.css (imported by input.css).

daisyUI's theme colours are made for fills - a primary button, with
--color-primary-content as the text on it. Soloblog also uses several as
text on the page itself: accent section labels, primary links, success/
warning/error status lines, and base-content at 40-70% for quieter text.
In many themes those are hard to read (cmyk's yellow labels: 1.01:1).
For each theme this works out, against both backgrounds text sits on
(base-100 cards, the base-200 page):

- --tx-<colour>: the colour moved towards the theme's own text colour
  just enough to reach 4.5:1 (WCAG AA) - unchanged where it already does;
  on its soft badge's tint too (.badge-soft, input.css)
- --tx-muted-<n>: base-content at the lowest opacity, from n% up, that
  reaches 4.5:1
- --color-<fill>-content: the text on a fill, moved towards black or
  white until it reaches 4.5:1, where daisyUI's own falls short
- --mark-bg / --mark-text: ==highlight==, readable - see highlight()
- --selection: the editor's selected text - see selection()

Run it after a daisyUI update (the themes' colours come from the built
CSS), then build the CSS again:

    python tools/theme_contrast.py
"""
from pathlib import Path
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from soloblog.themes import DAISYUI_THEMES, readable, theme_colours  # noqa: E402

def main():
    css = Path(os.path.join(ROOT, "static", "css", "output.css")).read_text(encoding="utf-8")
    out = ["/* Generated by tools/theme_contrast.py - run it again rather than",
           "   editing this. Per theme: text colours moved just enough to read",
           "   at 4.5:1 on the page and on cards, fill text that reaches it,",
           "   and the editor's selected text. */", ""]
    for name in DAISYUI_THEMES:
        colours = theme_colours(css, name)
        if "base-content" not in colours:
            print(f"no colours found for {name}")
            continue
        lines = readable(colours)
        if lines:
            out.append(f'html[data-theme="{name}"] {{')
            out += [f"  {line}" for line in lines]
            out.append("}")
    path = os.path.join(ROOT, "static", "css", "contrast.css")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
